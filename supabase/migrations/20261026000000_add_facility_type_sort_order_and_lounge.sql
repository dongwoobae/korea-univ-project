-- 화면들이 종류를 정렬 없이 읽어 저장 순서대로 보였다. 아래에서 restroom 행을 고치면 Postgres가 그 행을 새로 써 순서가 바뀐다.
-- 번호 없이 들어오는 종류는 다음 번호를 받아 맨 뒤에 붙는다.
alter table public.facility_types add column sort_order integer generated by default as identity;

-- 채우기가 종류마다 변경 기록을 남기지 않게 그동안만 끈다. 번호는 2026-10-26 운영 화면의 순서다.
alter table public.facility_types disable trigger log_facility_types_change;
update public.facility_types
set sort_order = case code
  when 'restroom' then 1
  when 'ramp' then 2
  when 'parking' then 3
  when 'elevator' then 4
  when 'automatic_door' then 5
end
where code in ('restroom', 'ramp', 'parking', 'elevator', 'automatic_door');
alter table public.facility_types enable trigger log_facility_types_change;

-- 운영에는 restroom이 있고 로컬·CI의 빈 DB에는 없다. 있으면 한국어 이름만 바꿔 운영의 영어·중국어 이름을 둔다.
insert into public.facility_types (code, label, label_en, label_zh)
values ('restroom', '장애인용 화장실', 'Accessible Restroom', '无障碍卫生间')
on conflict (code) do update set label = excluded.label;

insert into public.facility_types (code, label, label_en, label_zh)
values ('student_lounge', '장애학생 휴게실', 'Lounge for Students with Disabilities', '残障学生休息室')
on conflict (code) do update
  set label = excluded.label, label_en = excluded.label_en, label_zh = excluded.label_zh;

-- 화면은 시설 이름이 있으면 종류 이름보다 먼저 쓴다. 영어·중국어 이름과 번역 상태는 뜻이 같아 그대로 둔다.
update public.building_facilities
set name = '장애인용 화장실'
where name = '장애인 화장실';
